// Build/check the explicit native inventory; no test may silently miss the gate.
const root = new URL('../', import.meta.url);
const entries: { path: string; name: string }[] = [];
for await (const file of Deno.readDir(new URL('tests/', root))) {
  if (!file.isFile || !file.name.endsWith('.goose')) continue;
  const source = await Deno.readTextFile(new URL(`tests/${file.name}`, root));
  for (const match of source.matchAll(/^fn (test_[a-zA-Z0-9_]+)\(\)\s*\{/gm)) entries.push({ path: file.name, name: match[1] });
}
entries.sort((a, b) => a.path.localeCompare(b.path) || a.name.localeCompare(b.name));
if (!entries.length || new Set(entries.map(x => x.name)).size !== entries.length) throw new Error('invalid native test inventory');
const imports = [...new Set(entries.map(x => `import tests.${x.path.slice(0, -6)};`))];
const generated = [
  '// Generated by scripts/test_inventory.ts from explicit zero-argument test entries.',
  'import os;', ...imports, 'fn main() {',
  ...entries.flatMap(x => [
    `    print("BLOT_TEST_BEGIN ${x.name}");`,
    `    let start_${x.name} = clock_ns();`,
    `    ${x.name}();`,
    `    print("BLOT_TEST_END ${x.name} ", clock_ns() - start_${x.name});`,
  ]),
  `    print("BLOT_TEST_COMPLETE ${entries.length}");`, '}', '',
].join('\n');
if (Deno.args.includes('--write')) await Deno.writeTextFile(new URL('test.goose', root), generated);
else if (await Deno.readTextFile(new URL('test.goose', root)) !== generated) throw new Error('stale native inventory; run deno run --allow-read --allow-write scripts/test_inventory.ts --write');
const logArg = Deno.args.find(x => x.startsWith('--log='));
if (logArg) {
  const log = await Deno.readTextFile(logArg.slice(6));
  const begun = [...log.matchAll(/^BLOT_TEST_BEGIN (\S+)$/gm)].map(x => x[1]);
  const ended = [...log.matchAll(/^BLOT_TEST_END (\S+) ([0-9]+)$/gm)].map(x => x[1]);
  const expected = entries.map(x => x.name).join('\n');
  if (begun.join('\n') !== expected || ended.join('\n') !== expected || !log.includes(`BLOT_TEST_COMPLETE ${entries.length}\n`)) throw new Error('incomplete or mismatched native evidence');
  console.log(`verified ${entries.length} native entries with complete timing evidence`);
}
