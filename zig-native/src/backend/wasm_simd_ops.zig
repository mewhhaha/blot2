//! Strict four-lane operations from the core WebAssembly SIMD specification.
//! https://webassembly.github.io/spec/core/appendix/index-instructions.html
const w = @import("wasm.zig");
pub fn code(op: w.Op) ?u32 {
    return switch (op) {
        .v128_load => 0x00,
        .v128_store => 0x0b,
        .i32x4_splat => 0x11,
        .f32x4_splat => 0x13,
        .i32x4_replace_lane => 0x1c,
        .i32x4_extract_lane => 0x1b,
        .f32x4_extract_lane => 0x1f,
        .f32x4_replace_lane => 0x20,
        .i32x4_add => 0xae,
        .i32x4_sub => 0xb1,
        .i32x4_mul => 0xb5,
        .v128_and => 0x4e,
        .v128_or => 0x50,
        .v128_xor => 0x51,
        .f32x4_abs => 0xe0,
        .f32x4_neg => 0xe1,
        .f32x4_ceil => 0x67,
        .f32x4_floor => 0x68,
        .f32x4_trunc => 0x69,
        .f32x4_sqrt => 0xe3,
        .f32x4_add => 0xe4,
        .f32x4_sub => 0xe5,
        .f32x4_mul => 0xe6,
        .f32x4_div => 0xe7,
        .f32x4_convert_i32x4_u => 0xfb,
        .i32x4_trunc_sat_f32x4_u => 0xf9,
        .f32x4_convert_i32x4_s => 0xfa,
        .i32x4_trunc_sat_f32x4_s => 0xf8,
        .i8x16_shuffle => 0x0d,
        .i32x4_eq => 0x37,
        .i32x4_ne => 0x38,
        .i32x4_lt_u => 0x3a,
        .i32x4_gt_u => 0x3c,
        .i32x4_le_u => 0x3e,
        .i32x4_ge_u => 0x40,
        .f32x4_eq => 0x41,
        .f32x4_ne => 0x42,
        .f32x4_lt => 0x43,
        .f32x4_gt => 0x44,
        .f32x4_le => 0x45,
        .f32x4_ge => 0x46,
        .v128_not => 0x4d,
        .v128_andnot => 0x4f,
        .v128_bitselect => 0x52,
        .v128_any_true => 0x53,
        .i32x4_all_true => 0xa3,
        .i32x4_shl => 0xab,
        .i32x4_shr_s => 0xac,
        .i32x4_shr_u => 0xad,
        .i32x4_min_u => 0xb7,
        .i32x4_max_u => 0xb9,
        .f32x4_pmin => 0xea,
        .f32x4_pmax => 0xeb,
        // Relaxed SIMD: https://github.com/WebAssembly/relaxed-simd
        .f32x4_relaxed_madd => 0x105,
        .f32x4_relaxed_nmadd => 0x106,
        else => null,
    };
}
