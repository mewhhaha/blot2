// Sampling profile of blotc builds, for attributing compile time to code:
//
//   deno task profile:compile [--blotc zig-native/zig-out/bin/blotc]
//     [--workload game|devtools] [--test tests/NAME.blot] [--edit SCENARIO]
//     [--runs 3] [--reps 10] [--min-ms 3] [--max-ms 10] [--top 40]
//     [--snapshot DIR] [--out DIR]
//   deno task profile:compile --aggregate SAMPLES.jsonl... [--top 40]
//
// gdb (scripts/bench/gdb_sampler.py) attaches to the serve-project child that
// the project client opens, stops it at random intervals and records every
// thread's stack, inlined frames included. Cold mode samples one fresh build
// per run; --edit populates the session unsampled, then samples --reps
// edit/revert pairs of a retained scenario. The report has self, inclusive,
// subsystem, file, line and caller-attribution tables. A wrapper allows the
// attach under Yama ptrace_scope=1 (PR_SET_PTRACER) and then execs blotc.
// Requires Linux, gdb and python3, and a blotc with DWARF (release builds keep
// it). Samples stay in the output directory: they name compiler functions and
// files only, never gdev source.
import { parseArgs } from "node:util";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createZigProjectCompiler } from "../../compiler/zig_project_client.ts";
import {
  editedSources,
  gdevWorkloads,
  sessionOptions,
  testWorkloads,
  type Workload,
} from "./gdev.ts";

const repo = resolve(fileURLToPath(new URL("../..", import.meta.url)));
const usage = `Usage: deno task profile:compile [--blotc BLOTC]
  [--workload game|devtools] [--test tests/NAME.blot] [--edit SCENARIO]
  [--runs 3] [--reps 10] [--min-ms 3] [--max-ms 10] [--top 40]
  [--snapshot DIR] [--out DIR] [--codegen-workers 4]
       deno task profile:compile --aggregate SAMPLES.jsonl... [--top 40]
Results: build/tmp/profile/<timestamp>/{samples.jsonl,report.txt}.`;

const { values: args, positionals } = parseArgs({
  allowPositionals: true,
  options: {
    blotc: { type: "string" },
    workload: { type: "string", default: "game" },
    test: { type: "string" },
    edit: { type: "string" },
    runs: { type: "string", default: "3" },
    reps: { type: "string", default: "10" },
    "min-ms": { type: "string", default: "3" },
    "max-ms": { type: "string", default: "10" },
    top: { type: "string", default: "40" },
    snapshot: { type: "string" },
    out: { type: "string" },
    "codegen-workers": { type: "string", default: "4" },
    aggregate: { type: "boolean", default: false },
    help: { type: "boolean", default: false },
  },
});
const codegenWorkers = Number(args["codegen-workers"]);
if (
  !Number.isInteger(codegenWorkers) || codegenWorkers < 1 || codegenWorkers > 16
) {
  throw new Error("--codegen-workers must be an integer from 1 to 16");
}

// ------------------------------------------------------------------ sampling

const sleep = (ms: number) => new Promise((done) => setTimeout(done, ms));
async function exists(path: string): Promise<boolean> {
  try {
    await Deno.stat(path);
    return true;
  } catch (error) {
    if (error instanceof Deno.errors.NotFound) return false;
    throw error;
  }
}
async function waitFor(path: string, gdb: Deno.ChildProcess, what: string) {
  let exited = false;
  gdb.status.then(() => exited = true);
  for (let waited = 0; waited < 120_000; waited += 10) {
    if (await exists(path)) return;
    if (exited) throw new Error(`gdb exited before it ${what}; see its log`);
    await sleep(10);
  }
  throw new Error(`gdb did not ${what} within two minutes`);
}

/** Lets gdb attach under Yama ptrace_scope=1, then execs blotc unchanged. */
async function ptracerWrapper(out: string, blotc: string): Promise<string> {
  const path = `${out}/blotc-ptracer`;
  await Deno.writeTextFile(
    path,
    `#!/usr/bin/env python3
# Generated by scripts/bench/profile_compile.ts.
import ctypes, os, sys
PR_SET_PTRACER, PR_SET_PTRACER_ANY = 0x59616D61, ctypes.c_ulong(-1).value
ctypes.CDLL(None).prctl(PR_SET_PTRACER, PR_SET_PTRACER_ANY, 0, 0, 0)
os.execv(${JSON.stringify(blotc)}, [${JSON.stringify(blotc)}] + sys.argv[1:])
`,
  );
  await Deno.chmod(path, 0o755);
  return path;
}

async function sampleRun(
  run: number,
  out: string,
  blotc: string,
  wrapper: string,
  workload: Workload,
): Promise<void> {
  const scenario = args.edit
    ? workload.scenarios.find((s) => s.name === args.edit)
    : undefined;
  if (args.edit && !scenario) {
    throw new Error(
      `No scenario ${args.edit}; known: ${
        workload.scenarios.map((s) => s.name).join(", ")
      }`,
    );
  }
  const edited = scenario ? await editedSources(workload, scenario) : undefined;
  const control = `${out}/control-${run}`;
  await Deno.mkdir(control, { recursive: true });
  const gdb = new Deno.Command("gdb", {
    args: [
      "-batch",
      "-q",
      "-x",
      `${repo}/scripts/bench/gdb_sampler.py`,
    ],
    env: {
      SAMPLE_CONTROL: control,
      SAMPLE_BINARY: blotc,
      SAMPLE_OUT: `${out}/samples.jsonl`,
      SAMPLE_MIN_MS: args["min-ms"]!,
      SAMPLE_MAX_MS: args["max-ms"]!,
    },
    stdout: "piped",
    stderr: "piped",
  }).spawn();
  const log = gdb.output().then(({ stdout, stderr }) =>
    Deno.writeFile(
      `${out}/gdb-${run}.log`,
      new Uint8Array([...stdout, ...stderr]),
    )
  );
  let compiler:
    | Awaited<ReturnType<typeof createZigProjectCompiler>>
    | undefined;
  let detached = false;
  try {
    compiler = await createZigProjectCompiler({
      ...sessionOptions(wrapper, workload),
      cacheDirectory: false,
      codegenWorkers,
      profileBackend: true,
    });
    const project = compiler;
    let sampling = false;
    const ticks = async () => {
      const stat = await Deno.readTextFile(`/proc/${project.pid}/stat`);
      const fields = stat.slice(stat.lastIndexOf(") ") + 2).trim().split(/\s+/);
      return Number(fields[11]) + Number(fields[12]);
    };
    const build = async (sources: Record<string, string>, label: string) => {
      const before = await ticks(), started = Date.now();
      const result = await project.build({
        sources: { ...workload.overlay, ...sources },
      });
      if (!result.success) {
        throw new Error(
          `${label} failed: ${JSON.stringify(result.diagnostics.slice(0, 2))}`,
        );
      }
      await Deno.writeTextFile(
        `${out}/builds.jsonl`,
        JSON.stringify({
          run,
          label,
          sampled: sampling,
          started_ms: started,
          finished_ms: Date.now(),
          cpu_ms: ((await ticks()) - before) * 10,
          cpu_accounting: "Linux USER_HZ=100 child user plus system ticks",
          codegen_workers: codegenWorkers,
          stats: result.stats,
        }) + "\n",
        { append: true },
      );
    };
    let measured: () => Promise<void>;
    if (scenario && edited) {
      await build({}, "population");
      measured = async () => {
        for (let rep = 0; rep < Number(args.reps); rep++) {
          await build(edited, `edit ${scenario.name}`);
          await build({}, `revert ${scenario.name}`);
        }
      };
    } else measured = () => build({}, "cold build");
    // The wrapper execs blotc in place, so the client's pid is the compiler.
    await Deno.writeTextFile(`${control}/pid`, String(compiler.pid));
    await waitFor(`${control}/attached`, gdb, "attached");
    await sleep(150);
    await Deno.writeTextFile(`${control}/start`, "1");
    sampling = true;
    await measured();
    await Deno.writeTextFile(`${control}/stop`, "1");
    await waitFor(`${control}/detached`, gdb, "detached");
    detached = true;
  } finally {
    if (!detached) {
      // Failure before the PID/start handshake must not leave gdb waiting
      // forever and hide the original error while awaiting its output.
      try {
        gdb.kill("SIGTERM");
      } catch { /* The sampler may already have exited. */ }
    }
    await compiler?.dispose();
    await log;
  }
  console.log(
    `run ${run}: ${await Deno.readTextFile(`${control}/detached`)} samples`,
  );
}

// --------------------------------------------------------------- aggregation

/** Function, file, line, inlined. Innermost frame first. */
type Frame = [string, string, number, boolean];

async function loadStacks(files: string[]): Promise<Frame[][]> {
  const stacks: Frame[][] = [];
  for (const file of files) {
    for (const line of (await Deno.readTextFile(file)).split("\n")) {
      if (!line.trim()) continue;
      for (const stack of JSON.parse(line).st as Frame[][]) {
        if (stack.length) stacks.push(stack);
      }
    }
  }
  return stacks;
}

const compilerFile = /zig-native\/src\/(.*)/;
function short(file: string): string {
  return file.match(compilerFile)?.[1] ??
    file.match(/\/lib\/(std\/.*)/)?.[1] ??
    file.match(/\/lib\/(compiler_rt.*)/)?.[1] ?? (file || "?");
}
const stdKinds: [string, string][] = [
  ["heap", "allocator"],
  ["mem/Allocator", "allocator"],
  ["hash_map", "hash map"],
  ["array_hash_map", "hash map"],
  ["hash", "hash function"],
  ["mem.zig", "mem"],
  ["sort", "sort"],
  ["array_list", "array list"],
  ["Io", "io"],
  ["fmt", "fmt"],
  ["unicode", "unicode"],
];
function subsystem(file: string): string {
  const path = short(file);
  if (path.startsWith("compiler_rt")) return "compiler_rt (memcpy/memset)";
  if (path.startsWith("std/")) {
    for (const [key, name] of stdKinds) {
      if (path.includes(key)) return `std: ${name}`;
    }
    return "std: other";
  }
  if (!compilerFile.test(file)) return path;
  return path.includes("/") ? path.split("/")[0] : path;
}
/** Kinds of leaf time, attributed to the compiler function that called it. */
const leafKinds: [string, (file: string) => boolean][] = [
  ["memcpy/memset", (file) => file.includes("compiler_rt")],
  [
    "hash map",
    (file) => file.includes("std/hash_map") || file.includes("array_hash_map"),
  ],
  [
    "hash function",
    (file) => file.includes("std/hash/") || file.includes("blake3"),
  ],
  [
    "allocator",
    (file) => file.includes("std/heap") || file.includes("mem/Allocator"),
  ],
  ["array list", (file) => file.includes("std/array_list")],
];

function counter() {
  const counts = new Map<string, number>();
  return {
    add(key: string) {
      counts.set(key, (counts.get(key) ?? 0) + 1);
    },
    top(limit: number) {
      return [...counts].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))
        .slice(0, limit);
    },
  };
}

function report(stacks: Frame[][], top: number): string {
  const total = stacks.length;
  const lines: string[] = [
    `samples ${total}`,
    "Unweighted stack inventory; idle threads count. Use raw per-thread cpu_ns for CPU attribution.",
  ];
  if (!total) return lines.join("\n");
  const percent = (count: number) =>
    `${(100 * count / total).toFixed(1).padStart(5)}%`;
  const table = (title: string, rows: [string, number][]) => {
    lines.push("", `== ${title}`);
    for (const [key, count] of rows) lines.push(`${percent(count)}  ${key}`);
  };
  const owner = (stack: Frame[]) =>
    stack.find(([, file]) => compilerFile.test(file));
  const self = counter(), inclusive = counter(), selfSubsystem = counter();
  const ownerDirectory = counter(), inclusiveSubsystem = counter();
  const selfFile = counter(), selfLine = counter(), inclusiveFile = counter();
  for (const stack of stacks) {
    const [name, file, line] = stack[0];
    self.add(name);
    selfLine.add(`${name}  ${short(file)}:${line}`);
    selfSubsystem.add(subsystem(file));
    selfFile.add(short(file));
    const seen = new Set<string>();
    const seenSubsystems = new Set<string>();
    const seenFiles = new Set<string>();
    for (const [frameName, frameFile] of stack) {
      if (!seen.has(frameName)) inclusive.add(frameName);
      seen.add(frameName);
      const kind = subsystem(frameFile);
      if (!seenSubsystems.has(kind)) inclusiveSubsystem.add(kind);
      seenSubsystems.add(kind);
      if (compilerFile.test(frameFile) && !seenFiles.has(frameFile)) {
        inclusiveFile.add(short(frameFile));
      }
      seenFiles.add(frameFile);
    }
    const owned = owner(stack);
    ownerDirectory.add(owned ? subsystem(owned[1]) : "(no compiler frame)");
  }
  table("SELF by function", self.top(top));
  table("INCLUSIVE by function", inclusive.top(top));
  table(
    "SELF by leaf subsystem (innermost frame's file)",
    selfSubsystem.top(25),
  );
  table(
    "SELF by owning compiler directory (innermost frame in zig-native/src)",
    ownerDirectory.top(25),
  );
  table("INCLUSIVE by subsystem", inclusiveSubsystem.top(25));
  table("SELF by file", selfFile.top(25));
  table("INCLUSIVE by compiler file", inclusiveFile.top(top));
  table("SELF hot lines", selfLine.top(20));
  for (const [kind, matches] of leafKinds) {
    const callers = counter();
    let count = 0;
    for (const stack of stacks) {
      if (!matches(stack[0][1])) continue;
      count += 1;
      callers.add(owner(stack)?.[0] ?? "(no compiler frame)");
    }
    table(
      `${kind}: ${percent(count).trim()} of samples; top compiler callers`,
      callers.top(10),
    );
  }
  return lines.join("\n");
}

// ------------------------------------------------------------------- driver

async function main(): Promise<number> {
  if (args.help) {
    console.log(usage);
    return 0;
  }
  const top = Number(args.top);
  if (args.aggregate) {
    if (!positionals.length) {
      console.log(usage);
      return 2;
    }
    console.log(report(await loadStacks(positionals), top));
    return 0;
  }
  if (Deno.build.os !== "linux") throw new Error("profile:compile needs Linux");
  const blotc = resolve(args.blotc ?? `${repo}/zig-native/zig-out/bin/blotc`);
  const snapshotRoot = resolve(
    args.snapshot ?? `${repo}/build/bench/gdev-snapshot`,
  );
  // Tests build as pen builds them: the fixture entry with the test overlaid.
  const workloads = args.test
    ? await testWorkloads(repo, snapshotRoot)
    : await gdevWorkloads(repo, snapshotRoot);
  const name = args.test ?? args.workload;
  const workload = workloads.find((w) => w.name === name);
  if (!workload) throw new Error(`No gdev workload ${name}`);
  const timestamp = new Date().toISOString().replaceAll(":", "-").replace(
    /\..*/,
    "",
  );
  const out = resolve(args.out ?? `${repo}/build/tmp/profile/${timestamp}`);
  await Deno.mkdir(out, { recursive: true });
  if (
    await exists(`${out}/samples.jsonl`) || await exists(`${out}/metadata.json`)
  ) {
    throw new Error(
      "Profile output already contains a run; choose a new --out directory",
    );
  }
  const pins: Record<string, string> = {};
  for (
    const path of [
      blotc,
      fileURLToPath(import.meta.url),
      `${repo}/scripts/bench/gdb_sampler.py`,
      `${repo}/scripts/bench/gdev-manifest.json`,
    ]
  ) {
    const digest = await crypto.subtle.digest(
      "SHA-256",
      await Deno.readFile(path),
    );
    pins[path] = [...new Uint8Array(digest)].map((byte) =>
      byte.toString(16).padStart(2, "0")
    ).join("");
  }
  await Deno.writeTextFile(
    `${out}/metadata.json`,
    JSON.stringify(
      {
        pins,
        workload: name,
        snapshot: snapshotRoot,
        codegen_workers: codegenWorkers,
        cache_directory: false,
        profile_backend: true,
        args,
        attribution:
          "Report tables count stacks including idle threads; raw cpu_ns records per-thread scheduler CPU deltas",
      },
      null,
      2,
    ) + "\n",
  );
  const wrapper = await ptracerWrapper(out, blotc);
  for (let run = 0; run < Number(args.runs); run++) {
    await sampleRun(run, out, blotc, wrapper, workload);
  }
  const text = report(await loadStacks([`${out}/samples.jsonl`]), top);
  await Deno.writeTextFile(`${out}/report.txt`, text + "\n");
  console.log(text);
  console.log(`\nwrote ${out}/report.txt`);
  return 0;
}

Deno.exit(await main());
