#!/usr/bin/env python3
"""Generate complete read-only publication StampViews from retained typed runs."""
import argparse, hashlib, json, re
from pathlib import Path
from source_model import balanced, clean, fields

SCHEMAS=[('check/core','EffectRows'),('check/capability_contracts','Collection'),('check/core','TypesStampView'),('check/core','StampView')]
SCALARS={'bool','u8','u16','u32','u64','i64','f32','f64'}

def generate(root):
    cache={}; by_namespace={}
    for path in sorted(root.rglob('*.goose')):
        text=path.read_text(); m=re.search(r'\bnamespace\s+(\w+)\s*;',text)
        if m: by_namespace.setdefault(m[1],[]).append(path)
    def module(path):
        path=path.resolve()
        if path not in cache:
            text=clean(path.read_text()); ns=re.search(r'\bnamespace\s+(\w+)\s*;',text)[1]
            aliases=dict(re.findall(r'\btype\s+(\w+)\s*=\s*([^;]+);',text))
            cache[path]=(text,ns,aliases)
        return cache[path]
    def resolve(raw,path):
        raw=re.sub(r'\s+','',raw)
        if raw in SCALARS:return raw
        text,ns,aliases=module(path)
        if '::' in raw:
            n,name=raw.rsplit('::',1)
            choices=by_namespace.get(n,[])
            for candidate in choices:
                body,_,a=module(candidate)
                if name in a:return resolve(a[name],candidate)
                if re.search(r'\b(?:struct|enum)\s+'+re.escape(name)+r'\b',body):return n+'::'+name
            raise ValueError('Unknown qualified type '+raw)
        if raw in aliases:return resolve(aliases[raw],path)
        if re.search(r'\b(?:struct|enum)\s+'+re.escape(raw)+r'\b',text):return ns+'::'+raw
        raise ValueError('Unknown type '+raw+' in '+str(path))
    payload=root/'reuse/dependency_payload.goose'; text,_,_=module(payload)
    mappings={}
    for m in re.finditer(r'fn mutable\(self_:const Owner&,values:const (.+?)\[:\]\)->.*?\{(.*?)\n}',text,re.S):
        element=resolve(m[1],payload); body=m[2]
        tag=re.search(r'match link.value \{(\w+) run=>',body)[1]
        pool=re.search(r'return (\w+)\.realloc_slice',body)[1]
        value=(tag,pool)
        if element in mappings:assert mappings[element]==value
        mappings[element]=value
    records=[]; used={}; coverage=[]
    for rel,name in SCHEMAS:
        path=root/(rel+'.goose');body,ns,_=module(path);m=re.search(r'\bstruct\s+'+name+r'\s*\{',body)
        members=fields(body[m.end():balanced(body,m.end()-1)])
        records.append((path,ns+'::'+name,members))
    known={q for _,q,_ in records}
    out=['// Generated by tools/write_dependency_stamp_view.py; no allocation or payload copies.',
         '// Reborrow complete journal allocations before selecting any borrowed subrange.',
         'namespace blot_backend_result_publication;','import backend.result_publication;',
         'import reuse.dependency_payload;','import check.core;','import check.capability_contracts;','import support.option;']
    constructors=[]
    for path,q,members in records:
        values=[]
        for name,raw in members:
            t=re.sub(r'\s+','',raw);value='value.'+name
            if t.startswith('const') and t.endswith('[:]'):
                element=resolve(t[5:-3],path);assert element in mappings,(q,name,element)
                used[element]=mappings[element]; value='registeredStampSlice(owner,'+value+')';kind='slice'
                coverage.append({'record':q,'field':name,'raw_type':raw,'kind':kind,'element':element,'run':mappings[element][0],'pool':mappings[element][1]})
            else:
                target=resolve(t,path)
                if target in known:value='registeredStampView(owner,'+value+')';kind='record'
                else:assert target in SCALARS,(q,name,target);kind='scalar'
                coverage.append({'record':q,'field':name,'raw_type':raw,'kind':kind,'type':target})
            values.append(name+':'+value)
        constructors += [f'fn registeredStampView(owner:Owner,value:{q})->{q} {{',
                         f' return {q}{{'+','.join(values)+'};','}']
    prefix='blot_reuse_dependency_payload::'
    for element,(tag,pool) in sorted(used.items()):
        P=prefix+pool
        out += [f'fn registeredStampSlice(owner:Owner,source:const {element}[:])->const {element}[:] {{',
                ' assert(valid(owner) && states[owner.slot-1].inputs_staged);',
                f' if source.len==0 {{return default<const {element}[:]>();}}',
                ' // Fast path: a full run or a prefix at the allocation start.',
                ' for journal in states[owner.slot-1].pins.journals {',
                f'  assert(journal.valid());var next={prefix}leases[journal.lease-1].head;',
                f'  while next!=0 {{let link={prefix}links[next-1];next=link.next;match link.value {{',
                f'   {tag} run=>{{if source.len<=run.values.len {{',
                f'    let a:const {element}& =source[0];let b:const {element}& =run.values[0];if a .==b {{',
                f'     let full={P}.realloc_slice(run.values,run.values.len);assert(blot_support::same_slice_identity(full,run.values));',
                f'     let start={P}.index_of(full[0]);assert(start>=0 && full.len<={P}.len-start);',
                f'     let result={P}[start..start+source.len];assert(blot_support::same_slice_identity(result,source));return result;',
                '    }', '   }},_=>{},','  }}',' }',
                ' // Interior view: recover full capacity first; never resize a prefix.',
                ' for journal in states[owner.slot-1].pins.journals {',
                f'  assert(journal.valid());var next={prefix}leases[journal.lease-1].head;',
                f'  while next!=0 {{let link={prefix}links[next-1];next=link.next;match link.value {{',
                f'   {tag} run=>{{if source.len<run.values.len {{',
                f'    let full={P}.realloc_slice(run.values,run.values.len);assert(blot_support::same_slice_identity(full,run.values));',
                f'    let start={P}.index_of(full[0]);assert(start>=0 && full.len<={P}.len-start);',
                f'    for offset in 1..full.len-source.len+1 {{let result={P}[start+offset..start+offset+source.len];if blot_support::same_slice_identity(result,source) {{return result;}}}}',
                '   }},_=>{},','  }}',' }',
                ' abort("stamp view must belong to a journal pinned by this publication");','}']
    out+=constructors
    out += ['fn registeredInputHeader(owner:Owner,index:i64)->blot_check_core::StampView {',
            ' let units,error=registeredInputUnits(owner);assert(error==blot_error::Error.none && index>=0 && index<units.len);',
            ' let owned=module_runs.realloc_slice(units,units.len);assert(blot_support::same_slice_identity(owned,units));let start=module_runs.index_of(owned[0]);',
            ' return registeredStampView(owner,blot_check_core::stampView(module_runs[start+index]));','}']
    generated='\n'.join(out)+'\n'
    manifest={'records':[{'type':q,'fields':[n for n,_ in members]} for _,q,members in records],
              'fields':coverage,'field_count':len(coverage),'slice_field_count':sum(x['kind']=='slice' for x in coverage),
              'concrete_slice_types':len(used),'pool_mappings':{t:{'run':x[0],'pool':x[1]} for t,x in sorted(used.items())},
              'schema_hashes':{str(p.relative_to(root)):hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted({p for p,_,_ in records}|{payload})},
              'generated_sha256':hashlib.sha256(generated.encode()).hexdigest()}
    return generated,manifest

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--source-root',type=Path,default=Path(__file__).resolve().parents[1]/'src');parser.add_argument('--manifest',type=Path);args=parser.parse_args()
    generated,manifest=generate(args.source_root)
    (args.source_root/'reuse/dependency_stamp_view.goose').write_text(generated)
    if args.manifest:args.manifest.write_text(json.dumps(manifest,indent=2)+'\n')

if __name__=='__main__':main()
