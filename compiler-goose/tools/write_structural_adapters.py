"""Emit explicit struct hooks; Goose ranks generic overloads without specificity."""
from pathlib import Path
import re
import sys
from source_model import clean, balanced, split

ROOT = Path(__file__).resolve().parents[1] / 'src'
TARGET = ROOT / 'support/structural_adapters.goose'
# Concrete equality covers only explicitly selected private domains. Tagged
# enums compare their active payload fields, never owner addresses or padding.
ENUM_EQUALITY = {
    'blot_backend_layout::Tag': ('backend/layout.goose', 'Tag'),
    'blot_eval_eval_values::ValueKind': ('eval/eval_values.goose', 'ValueKind'),
    'blot_eval_eval_values::ClosureOrigin': ('eval/eval_values.goose', 'ClosureOrigin'),
    'blot_eval_type_evidence::Tag': ('eval/type_evidence_schema.goose', 'Tag'),
    'blot_eval_implementation_evidence::ProofKind': ('eval/implementation_evidence.goose', 'ProofKind'),
    'blot_reuse_code_artifacts::Request': ('reuse/code_artifacts.goose', 'Request'),
    'blot_reuse_code_artifacts::OperationLocation': ('reuse/code_artifacts.goose', 'OperationLocation'),
}
def enum_equalities():
    result={}
    for qualified,(path,name) in ENUM_EQUALITY.items():
        source=clean((ROOT/path).read_text());match=re.search(r'\benum\s+'+name+r'\s*\{',source);opening=match.end()-1
        variants=[]
        for part in split(source[opening+1:balanced(source,opening)]):
            variant=re.match(r'\s*(\w+)',part)[1]
            fields=[]
            if '{' in part:
                for field in split(part[part.index('{')+1:part.rindex('}')]):
                    found=re.match(r'\s*(\w+)\s*:',field)
                    if found:fields.append(found[1])
            variants.append((variant,fields))
        prefix='fn equal(left:'+qualified+',right:'+qualified+')->bool {'
        if not any(fields for _,fields in variants):result[qualified]=prefix+'return left==right;}'
        else:
            arms=[]
            for variant,fields in variants:
                check='true'
                if fields:check=' && '.join('equal(a.'+field+',b.'+field+')' for field in fields)
                payload=' a' if fields else '';other=' b' if fields else ''
                arms.append(variant+payload+'=>{match right {'+variant+other+'=>{return '+check+';},_=>{return false;}}},')
            result[qualified]=prefix+'match left {'+''.join(arms)+'}}'
    return result
if sys.argv[1:]==['--repair-enum-equality']:
    source=TARGET.read_text();count=0
    for name,hook in enum_equalities().items():
        if re.search(r'fn equal(?:<[^>]+>)?\(left:[^,]+,\s*right:\s*'+re.escape(name)+r'\)',source):continue
        source+='\n'+hook+'\n';count+=1
    TARGET.write_text(source);print('Added',count,'enum equality hooks');raise SystemExit(0)
structs = {}
custom_equal = set()
custom_hash = set()
for path in sorted(ROOT.rglob('*.goose')):
    if path == TARGET or path.name.startswith('_') or (path.parent == ROOT and 'probe' in path.stem):
        continue
    source = path.read_text()
    namespace = re.search(r'\bnamespace\s+(\w+)\s*;', source)
    if namespace is None:
        continue
    ns = namespace[1]
    module = path.relative_to(ROOT).with_suffix('').as_posix().replace('/', '.')
    for declaration in re.finditer(r'\bstruct\s+(\w+)(?:<([^>{}]+)>)?\s*\{', source):
        name, generic = declaration.groups()
        qualified = ns + '::' + name
        if generic:
            qualified += '<' + generic + '>'
        structs[qualified] = generic, module
    for declaration in re.finditer(r'\bfn\s+blot_structural::(equal|hash)(?:<[^>]+>)?\s*\([^)]*\)', source):
        # Existing hooks use concrete qualified types. Keep their source-shaped
        # enum widths and union payload rules instead of replacing them.
        types = re.findall(r':\s*(blot_\w+::\w+(?:<[^>]+>)?)', declaration[0])
        if types:
            if declaration[1] == 'equal':
                custom_equal.add(types[-1])
            else:
                custom_hash.add(types[-1])

excluded = {'blot_support::Option<T>'}
selected = [(name, generic, module) for name, (generic, module) in sorted(structs.items()) if name not in excluded]
out = ['// Generated by tools/write_structural_adapters.py.',
       '// Explicit heads avoid equally ranked catch-all generic overloads.',
       'namespace blot_structural;', 'import support.structural;']
out.extend('import ' + module + ';' for module in sorted({module for _, _, module in selected}))
for name, generic, _ in selected:
    parameters = '<StructuralLeft'
    if generic:
        parameters += ',' + generic
    parameters += '>'
    if name not in custom_equal:
        out.append('fn equal' + parameters + '(left:StructuralLeft,right:' + name + ')->bool {return equalFields(left,right);}')
    if name not in custom_hash:
        parameters = '<StructuralSink'
        if generic:
            parameters += ',' + generic
        parameters += '>'
        out.append('fn hash' + parameters + '(sink:StructuralSink&,value:' + name + ') {hashFields(sink,value);}')
# These native anonymous/implicit enum tags occupy one byte. Their ordinal
# order is pinned by compiler/src/reuse/principal_interface.zig and
# compiler/src/backend/opaque_storage.zig, respectively.
for name, variants in {
    'blot_reuse_principal_interface::Kind': ['global','local','parameter','external'],
    'blot_reuse_principal_interface::ContractMemberKind': ['defined_type','abstract_type','value'],
    'blot_reuse_principal_interface::ImplementationMemberKind': ['type_','value'],
    'blot_reuse_principal_interface::SelectedProofKind': ['implementation','predicate'],
    'blot_backend_opaque_storage::Kind': ['unknown','unit','boolean','unsigned32','floating32','reference','parameter'],
}.items():
    if name not in custom_equal:
        out.append('fn equal<StructuralLeft>(left:StructuralLeft,right:'+name+')->bool {return left==right;}')
    if name not in custom_hash:
        arms=[]
        for ordinal, variant in enumerate(variants):
            arms.append(variant+'=>{hash(sink,'+str(ordinal)+' as u8);},')
        out.append('fn hash<StructuralSink>(sink:StructuralSink&,value:'+name+') {match value {'+''.join(arms)+'}}')
for name,hook in enum_equalities().items():
    if name not in custom_equal:out.append(hook)
TARGET.write_text('\n'.join(out) + '\n')
