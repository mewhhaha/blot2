#!/usr/bin/env python3
"""Reconstruct Checked views through its existing local or retained packet owner."""
from pathlib import Path
import re
from source_model import balanced, clean, fields
ROOT = Path(__file__).resolve().parents[1] / 'src'

def members(file, name):
    text = clean((ROOT / file).read_text())
    match = re.search(r'\bstruct\s+' + name + r'\s*\{', text)
    return fields(text[match.end():balanced(text, match.end()-1)])

def qualify(raw_type, file):
    text = clean((ROOT / file).read_text())
    namespace = re.search(r'namespace\s+(\w+)\s*;', text)[1]
    names = set(re.findall(r'\b(?:struct|enum|type)\s+(\w+)', text))
    return re.sub(r'(?<![\w:])\b\w+\b(?!::)', lambda m: namespace+'::'+m[0] if m[0] in names else m[0], raw_type)

lines = ['// Generated by tools/write_checked_views.py; registered headers only, no copying.',
         'namespace blot_check_check;', 'import .check;', 'import .check_owners;',
         'import .check_packet_owner;', 'import check.types;', 'import check.parameter_patterns;',
         'import support.project_packet;', 'import support.option;', 'import reuse.hole_diagnostics;']
def run(field, journal, readonly=False, force_local=False):
    return f'checkedRun_{journal}(packet,value.{field},state.{journal})'

# The concrete packet owner retains immutable decoded tables; diagnostics are reowned.
used = {}
local_only = set()
def checked_run(raw_type, field, journal, force_local=False):
    if force_local:
        local_only.add(journal)
    used[journal] = raw_type
    return run(field, journal)

editor = []
for field, raw_type in members('check/check.goose', 'EditorCapture'):
    expression = 'value.' + field
    if field == 'names':
        expression = checked_run(raw_type, field, 'editor_names')
    elif field == 'context':
        expression = 'context'
    editor.append(field + ':' + expression)
lines += ['fn canonicalCheckedEditor(state:const CheckedOwnerState&,packet:blot_project_packet::Owner,value:EditorCapture)->EditorCapture {',
          ' var context=blot_support::none<blot_reuse_hole_diagnostics::Snapshot>();if value.context.present {context=blot_support::Option<blot_reuse_hole_diagnostics::Snapshot>{true,blot_reuse_hole_diagnostics::canonicalOwned(value.context.value)};}',
          ' return EditorCapture{' + ','.join(editor) + '};', '}']
values = []
for field, raw_type in members('check/check.goose', 'Checked'):
    expression = 'value.' + field
    if '[:]' in raw_type:
        expression = checked_run(raw_type, field, field, field == 'diagnostics')
    elif field == 'types':
        expression = 'blot_check_types::checkedView(value.types)'
    elif field == 'parameter_patterns':
        expression = 'blot_check_parameter_patterns::checkedView(value.parameter_patterns)'
    elif field in ['proof_bodies', 'capability_contracts']:
        file, name, prefix = ('check/numeric_proof_bodies.goose', 'Owned', 'body_')
        if field == 'capability_contracts':
            file, name, prefix = ('check/capability_contracts.goose', 'Collection', 'cap_')
        nested = []
        for child, child_type in members(file, name):
            child_type = qualify(child_type, file)
            if '[:]' not in child_type:
                raise ValueError((field, child, child_type))
            nested.append(child + ':' + checked_run(child_type, field + '.' + child, prefix + child))
        typename = raw_type
        expression = typename + '{' + ','.join(nested) + '}'
    elif field == 'editor':
        expression = 'editor'
    elif field not in ['owner', 'initializer_rejected', 'body_elaborations', 'imported_schemes', 'counters', 'unit']:
        raise ValueError((field, raw_type))
    values.append(field + ':' + expression)
lines += ['fn canonicalOwnedChecked(value:Checked)->Checked {',
          ' let state:const CheckedOwnerState& =checkedOwnerState(value.owner);let packet=checkedPacket(value.owner);',
          ' var editor=blot_support::none<EditorCapture>();if value.editor.present {editor=blot_support::Option<EditorCapture>{true,canonicalCheckedEditor(state,packet,value.editor.value)};}',
          ' return Checked{' + ','.join(values) + '};', '}']
for journal, raw_type in used.items():
    method = 'view'
    if raw_type.strip().startswith('const '):
        method = 'readView'
    lines += [f'fn checkedRun_{journal}(packet:blot_project_packet::Owner,value:{raw_type},registered:{raw_type})->{raw_type} {{']
    if journal not in local_only:
        lines += [f' if packet.slot!=0 {{return blot_project_packet::{method}(packet,value);}}']
    lines += [' assert(blot_support::same_slice_identity(value,registered));',
              f' if value.len==0 {{return default<{raw_type}>();}}',
              f' let owned=checked_{journal}.realloc_slice(registered,registered.len);let start=checked_{journal}.index_of(owned[0]);',
              f' return checked_{journal}[start..start+owned.len];', '}']
(ROOT / 'check/checked_views.goose').write_text('\n'.join(lines)+'\n')
