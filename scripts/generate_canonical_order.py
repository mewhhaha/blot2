#!/usr/bin/env python3
import sys
"""Generate explicit identity relocation for canonical portable Core ordering."""
import runpy
from pathlib import Path
root=Path(__file__).resolve().parent.parent
schema=runpy.run_path(str(root/'scripts/generate_relocator.py'))
tables=schema['tables']; structs=schema['structs']; tags=schema['tags']; roles=schema['roles']; tag=schema['tag']
roles['functions']['export_id']='exports'
body='''// Generated by scripts/generate_canonical_order.py. No source checker state.
// External identities are sorted; private identities follow their explicit owner
// structure. Ref/byte arenas are rebuilt and version atoms alpha-normalized.
namespace core_order;
import src.model;
import src.canonical;
import src.hash;
import std;
struct Ref { table:u32, id:u32 }
struct Key { id:u32, bytes:Span }
struct Atom { old:u32, fresh:u32 }
fn canonical_order(c:Core,b:CoreBuilder)->bool {
    var visits:u64=0; let limit=(LIMIT_ARTIFACT as u64)*256;
    fn tick() { visits++; if visits>limit { return false from canonical_order; } }
'''
for n,t in tables:body+=f'    var map_{n}:u32[>..]=[]; for row in c.{n} {{ map_{n}.push(0); }}\n'
body+='''    var queue:Ref[>..]=[]; var cursor:i64=0;
    fn mapped(table:u32,id:u32)->u32 {
        if id==0 || table==0 { return id; }
'''
for n,t in tables:body+=f'        if table=={tags[n]} {{ if id>=map_{n}.len {{ return false from canonical_order; }} return map_{n}[id]; }}\n'
body+='''        return false from canonical_order; return 0;
    }
    fn mark(table:u32,id:u32) {
        tick(); if id==0 || table==0 || mapped(table,id)!=0 { return; }
'''
for n,t in tables:body+=f'        if table=={tags[n]} {{ map_{n}[id]=b.{n}.len as u32; b.{n}.push({t}{{..}}); }}\n'
body+='''        queue.push(Ref{table,id});
    }
    fn mark_span(table:u32,span:Span) { if !span_ok(span,c.refs.len) { return false from canonical_order; } for i in span.count { mark(table,c.refs[span.start+i]); } }
    fn operation_reference(op:u32)->u32 {
'''
body+=f'''        if op==OP_CALL || op==OP_CLOSURE || op==OP_FN_PLACE || op==OP_GENERIC_BIND {{ return {tags['functions']}; }}
        if op==OP_TRY_ALLOC || op==OP_LAYOUT_SIZE || op==OP_LAYOUT_ALIGN {{ return {tags['types']}; }}
        if op==OP_NAT_VALUE || op==OP_REGION_RESET {{ return {tags['binders']}; }}
        if op==OP_STATIC {{ return {tags['static_objects']}; }} return 0;
    }}
'''
body+='''    var key_bytes:u8[>..]=[];
    fn word(value:u32) { tick(); for i in 4 { key_bytes.push((value>>(24-i*8)) as! u8); } }
    fn string(bytes:const u8[:]) { tick(); word(bytes.len as u32); key_bytes.append(bytes); }
    fn origin(id:u32) { if id==0 {word(0);word(0);return;} let row=c.origins[id]; string(name_bytes(c,c.modules[row.module].path)); word(row.start); word(row.end); }
    fn type_key(id:u32) { if id==0 {word(0);return;} var bytes:u8[>..]=[]; if !canonical_interface(c,id,bytes) { return false from canonical_order; } string(bytes); }
    fn identity(id:u32) { if id==0 {word(0);return;} let row=c.definitions[id]; string(name_bytes(c,c.modules[row.module].path)); string(name_bytes(c,row.name)); word(row.kind); }
    fn key_less(a:Key,z:Key)->bool {
        let x=key_bytes[a.bytes.start..a.bytes.start+a.bytes.count]; let y=key_bytes[z.bytes.start..z.bytes.start+z.bytes.count];
        for i in min(x.len,y.len) { tick(); if x[i]!=y[i] {return x[i]<y[i];} } return x.len<y.len;
    }
    fn sort_keys(keys:Key[:]) { sort(keys) { a,z=>key_less(a,z) }; }
    fn append_key(keys:Key[>..]&,id:u32,start:u32) { if key_bytes.len>LIMIT_ARTIFACT*8 { return false from canonical_order; } keys.push(Key{id,Span{start,key_bytes.len as u32-start}}); }
    fn function_key(fid:u32) {
        let f=c.functions[fid]; identity(f.producer); string(name_bytes(c,f.name)); origin(f.origin); word(if f.evaluator_only {1}else{0}); type_key(f.type_id);
        // Explicit owner instruction order is independent of arena row IDs.
        for bi in f.blocks.count { let basic=c.blocks[c.refs[f.blocks.start+bi]]; origin(basic.origin); word(basic.params.count);
            for oi in basic.ops.count { let op=c.ops[c.refs[basic.ops.start+oi]]; word(op.tag); word(op.args.count); word(op.results.count);
                if operation_reference(op.tag)==0 {word(op.imm0);} else if op.tag==OP_CALL || op.tag==OP_CLOSURE || op.tag==OP_FN_PLACE || op.tag==OP_GENERIC_BIND {identity(c.functions[op.imm0].producer);}
                word(op.imm1); origin(op.origin);
            } word(c.terminators[basic.term].tag);
        }
    }
    fn drain() {
        while cursor<queue.len { tick(); let item=queue[cursor]; cursor++;
'''
for n,t in tables:
 body+=f'            if item.table=={tags[n]} {{ let row=c.{n}[item.id];\n'
 # Modules only preassigned definitions; source order remains in explicit spans.
 for f,ty in structs[t]:
  role=roles[n].get(f)
  if not role or role in ('bytes','raw','omit'):continue
  if n=='functions' and f=='blocks':continue
  if ty=='Span':body+=f'                mark_span({tag(role)},row.{f});\n'
  else:body+=f'                mark({tag(role)},row.{f});\n'
 body+='            }\n'
body+='''        }
    }
    // Sort external producer identities first. Their IDs are never discovered
    // opportunistically by whichever caller happens to be visited first.
    var keys:Key[>..]=[];
'''
body+=f'''    for row,id in c.modules {{ if id==0 {{continue;}} let start=key_bytes.len as u32; string(name_bytes(c,row.path)); string(name_bytes(c,row.name)); append_key(keys,id as u32,start); }}
    sort_keys(keys[..]); for key in keys {{mark({tags['modules']},key.id);}} keys.resize(0); key_bytes.resize(0);
    for row,id in c.definitions {{ if id==0 {{continue;}} let start=key_bytes.len as u32; identity(id as u32); append_key(keys,id as u32,start); }}
    sort_keys(keys[..]); for key in keys {{mark({tags['definitions']},key.id);}} keys.resize(0); key_bytes.resize(0);
    drain();
    // Exports retain manifest order because that ordinal is part of the wire ABI.
    for row,id in c.exports {{if id!=0 {{mark({tags['exports']},id as u32);}}}} drain();
    // All source bodies, including checked required-static staging functions,
    // remain independently owned even when they emit no executable body.
    for row,id in c.functions {{ if id==0 || map_functions[id]!=0 {{continue;}} let start=key_bytes.len as u32; function_key(id as u32); append_key(keys,id as u32,start); }}
    sort_keys(keys[..]); for key in keys {{mark({tags['functions']},key.id);}} keys.resize(0); key_bytes.resize(0); drain();
    // CFG links determine private block numbers, independently of arena/list
    // order. Disconnected optional-optimizer residue uses source anchors.
    var function_order:u32[>..]=[];for row in b.functions {{function_order.push(0);}}
    for row,id in c.functions {{if id!=0 {{tick();function_order[map_functions[id]]=id as u32;}}}}
    for original in function_order {{
        if original==0 {{continue;}}let f=c.functions[original];
        for i in f.blocks.count {{let id=c.refs[f.blocks.start+i];if map_blocks[id]!=0 {{continue;}}let basic=c.blocks[id];let start=key_bytes.len as u32;origin(basic.origin);word(basic.params.count);
            for oi in basic.ops.count {{let op=c.ops[c.refs[basic.ops.start+oi]];word(op.tag);if operation_reference(op.tag)==0 {{word(op.imm0);}}else{{word(mapped(operation_reference(op.tag),op.imm0));}}origin(op.origin);}}
            word(c.terminators[basic.term].tag);append_key(keys,id,start);
        }}sort_keys(keys[..]);for key in keys {{mark({tags['blocks']},key.id);}}keys.resize(0);key_bytes.resize(0);drain();
    }}
'''
# Root semantic and ABI metadata in stable keys, then follow owned graphs.
for n in ['static_objects','callable_adapters','interfaces','receipts','layouts','abi_plans','dictionary_realizations']:
 body+=f'    for row,id in c.{n} {{ if id==0 || map_{n}[id]!=0 {{continue;}} let start=key_bytes.len as u32;\n'
 if n=='static_objects':body+='        identity(row.producer); word(row.kind); type_key(row.type_id); string(c.bytes[row.bytes.start..row.bytes.start+row.bytes.count]); word(mapped('+str(tags['functions'])+',row.function)); word(mapped('+str(tags['ops'])+',row.constructor));\n'
 if n=='callable_adapters':body+=f'        word(mapped({tags["ops"]},row.op)); word(mapped({tags["functions"]},row.target_function));\n'
 if n=='interfaces':body+=f'        identity(row.producer); word(mapped({tags["functions"]},row.function)); type_key(row.type_id);\n'
 if n=='receipts':body+='        identity(row.producer); string(c.bytes[row.source_digest.start..row.source_digest.start+row.source_digest.count]);\n'
 if n=='layouts':body+=f'        word(mapped({tags["types"]},row.type_id)); type_key(row.type_id); word(row.size); word(row.align); word(row.flags); word(row.abi);\n'
 if n=='abi_plans':body+=f'        word(mapped({tags["functions"]},row.function)); word(mapped({tags["contracts"]},row.contract)); type_key(c.contracts[row.contract].arg); type_key(c.contracts[row.contract].result); word(row.frame); word(row.depth);\n'
 if n=='dictionary_realizations':body+=f'        word(mapped({tags["types"]},row.type_id)); type_key(row.type_id); for i in row.arguments.count {{type_key(c.refs[row.arguments.start+i]);}} type_key(row.concrete_type);\n'
 body+='        append_key(keys,id as u32,start);\n    }\n'
 body+=f'    sort_keys(keys[..]); for key in keys {{mark({tags[n]},key.id);}} keys.resize(0); key_bytes.resize(0); drain();\n'
body+=f'''    // Return and Boolean postconditions use scope-owned proofs even when no
    // operation references them. Keep that complete graph, ordered by content
    // and already-canonical SSA anchors rather than producer allocation order.
    var term_hashes:k1hash::Digest[>..]=[];term_hashes.push(k1hash::Digest{{..}});
    fn digest_words(value:k1hash::Digest) {{for w in value.words {{word(w);}}}}
    for row,id in c.terms {{if id==0 {{continue;}} key_bytes.resize(0);word(row.tag);word(row.literal);word(mapped({tags['values']},row.value));word(mapped({tags['scopes']},row.scope));
        if row.type_id!=0 {{type_key(row.type_id);}}else{{word(0);}}
        if row.tag==EXPR_ARG || row.tag==EXPR_RESULT {{word(mapped({tags['contracts']},row.binder));}}else{{word(mapped({tags['binders']},row.binder));}}
        word(row.args.count);for i in row.args.count {{let child=c.refs[row.args.start+i];if child>=id {{return false;}}digest_words(term_hashes[child]);}}
        term_hashes.push(k1hash::blake3(key_bytes));
    }}
    var fact_hashes:k1hash::Digest[>..]=[];fact_hashes.push(k1hash::Digest{{..}});
    for row,id in c.facts {{if id==0 {{continue;}}key_bytes.resize(0);word(row.tag);digest_words(term_hashes[row.left]);digest_words(term_hashes[row.right]);digest_words(term_hashes[row.third]);word(mapped({tags['binders']},row.domain));fact_hashes.push(k1hash::blake3(key_bytes));}}
    var proof_hashes:k1hash::Digest[>..]=[];var proof_seen:u32[>..]=[];for row in c.evidence {{proof_hashes.push(k1hash::Digest{{..}});proof_seen.push(0);}}
    var proof_stack:u32[>..<]=[];var proof_next:u32[>..<]=[];
    for row,id in c.evidence {{if id==0 || proof_seen[id]!=0 {{continue;}}proof_stack.push(id as u32);proof_next.push(0);proof_seen[id]=1;
        while proof_stack.len!=0 {{tick();let last=proof_stack.len-1;let current=proof_stack[last];let proof=c.evidence[current];let next=proof_next[last];
            if next<proof.premises.count {{proof_next[last]++;let child=c.refs[proof.premises.start+next];if proof_seen[child]==1 {{return false;}}if proof_seen[child]==0 {{proof_seen[child]=1;proof_stack.push(child);proof_next.push(0);}}}}
            else {{key_bytes.resize(0);word(proof.rule);digest_words(fact_hashes[proof.fact]);digest_words(fact_hashes[proof.formal_fact]);word(mapped({tags['scopes']},proof.scope));word(mapped({tags['edges']},proof.edge));word(mapped({tags['ops']},proof.call));word(mapped({tags['contracts']},proof.contract));
                word(proof.operands.count);for i in proof.operands.count {{word(mapped({tags['values']},c.refs[proof.operands.start+i]));}}word(proof.premises.count);for i in proof.premises.count {{digest_words(proof_hashes[c.refs[proof.premises.start+i]]);}}origin(proof.origin);
                proof_hashes[current]=k1hash::blake3(key_bytes);proof_seen[current]=2;proof_stack.pop();proof_next.pop();
            }}
        }}
    }}
    key_bytes.resize(0);for row,id in c.evidence {{if id==0 || map_evidence[id]!=0 {{continue;}}let start=key_bytes.len as u32;digest_words(proof_hashes[id]);append_key(keys,id as u32,start);}}
    sort_keys(keys[..]);for key in keys {{mark({tags['evidence']},key.id);}}keys.resize(0);key_bytes.resize(0);drain();
'''
body+='''    // Term IDs are canonical postorder so their required DAG invariant survives
    // every numbering change. Other cross references may point forward.
    var term_seen:u32[>..]=[]; for row in c.terms {term_seen.push(0);}
    var term_stack:u32[>..<]=[]; var term_next:u32[>..<]=[]; var term_order:u32[>..]=[];
'''
body+=f'''    for item in queue {{if item.table!={tags['terms']} || term_seen[item.id]!=0 {{continue;}} term_stack.push(item.id);term_next.push(0);term_seen[item.id]=1;
        while term_stack.len!=0 {{tick();let last=term_stack.len-1;let id=term_stack[last];let row=c.terms[id];let next=term_next[last];
            if next<row.args.count {{term_next[last]++;let child=c.refs[row.args.start+next];if term_seen[child]==1 {{return false;}}if term_seen[child]==0 {{term_seen[child]=1;term_stack.push(child);term_next.push(0);}}}}
            else {{term_seen[id]=2;term_order.push(id);map_terms[id]=term_order.len as u32;term_stack.pop();term_next.pop();}}
        }}
    }}
'''
body+='''    var atoms:Atom[>..]=[];var atom_slots:u32[>..]=[];var atom_capacity:u32=8;
    let atom_max=c.values.len+c.terms.len+c.facts.len;
    while atom_capacity<atom_max*2 {if atom_capacity>LIMIT_ARTIFACT {return false;}atom_capacity*=2;}
    for i in atom_capacity {atom_slots.push(0);}
    fn atom(old:u32)->u32 {
        if old==0 {return 0;}var slot=(old*0x9e3779b1)&(atom_capacity-1);
        while atom_slots[slot]!=0 {tick();let row=atoms[atom_slots[slot]-1];if row.old==old {return row.fresh;}slot=(slot+1)&(atom_capacity-1);}
        tick();let id=atoms.len as u32+1;atoms.push(Atom{old,id});atom_slots[slot]=id;return id;
    }
    // Assign value versions in canonical value order, preserving equality classes.
    var value_order:u32[>..]=[];for row in b.values {value_order.push(0);}
    for row,id in c.values {if id!=0 && map_values[id]!=0 {value_order[map_values[id]]=id as u32;}}
    for old in value_order {if old!=0 {atom(c.values[old].version);}}
    fn bytes(old:Span)->Span {
        if old.count==0 {return Span{..};} if !span_ok(old,c.bytes.len) || old.count>LIMIT_ARTIFACT-b.bytes.len {return false from canonical_order;}
        let result=Span{b.bytes.len as u32,old.count};b.bytes.append(c.bytes[old.start..old.start+old.count]);return result;
    }
    fn span(table:u32,old:Span)->Span {
        if old.count==0 {return Span{..};} if !span_ok(old,c.refs.len) || old.count>LIMIT_ARTIFACT/4-b.refs.len {return false from canonical_order;}
        let result=Span{b.refs.len as u32,old.count};for i in old.count {let original=c.refs[old.start+i];let id=mapped(table,original);if original!=0 && id==0 {return false from canonical_order;}b.refs.push(id);}return result;
    }
'''
for n,t in tables:
 body+=f'    for item in queue {{if item.table!={tags[n]} {{continue;}}let old=c.{n}[item.id];var row=old;\n'
 for f,ty in structs[t]:
  role=roles[n].get(f)
  if n=='functions' and f=='blocks':
   body+=f'        var ordered:u32[>..]=[]; for i in old.blocks.count {{ordered.push(mapped({tags["blocks"]},c.refs[old.blocks.start+i]));}} sort(ordered[..]) {{a,z=>a<z}}; row.blocks=ref_span(b,ordered);\n';continue
  if f=='version' and n in ('values','terms','facts'):body+=f'        row.{f}=atom(old.{f});\n';continue
  if not role:continue
  if role=='bytes':body+=f'        row.{f}=bytes(old.{f});\n'
  elif ty=='Span':body+=f'        row.{f}=span({0 if role=="raw" else tag(role,"old")},old.{f});\n'
  elif role=='omit':body+=f'        row.{f}=0;\n'
  else:body+=f'        row.{f}=mapped({tag(role,"old")},old.{f});\n'
 body+=f'        b.{n}[map_{n}[item.id]]=row;\n    }}\n'
body+='''    b.phase=c.phase; return true;
}
'''
destination=root/'src/order.goose'
if '--check' in sys.argv:
    if not destination.exists() or destination.read_text()!=body:
        print('stale generated file: '+str(destination),file=sys.stderr)
        raise SystemExit(1)
else:
    destination.write_text(body)
