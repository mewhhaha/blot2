import { dirname, resolve } from "node:path";
import {
  dataShapes,
  deriveCodec,
  deriveEqualityAndDebug,
  type DeriveSchema,
} from "../compiler/derive.ts";

function option(name: string): string {
  const index = Deno.args.indexOf(name);
  if (index < 0 || !Deno.args[index + 1]) {
    throw new Error(`Missing ${name}`);
  }
  return resolve(Deno.args[index + 1]);
}

async function check(
  compiler: string,
  source: string,
  stdRoot: string,
  prelude: string,
): Promise<void> {
  const run = await new Deno.Command(compiler, {
    args: [
      "check-project",
      source,
      "--std-root",
      stdRoot,
      "--prelude",
      prelude,
    ],
    stdout: "piped",
    stderr: "piped",
  }).output();
  if (run.success) return;
  const records = new TextDecoder().decode(run.stdout).trim().split("\n");
  const diagnostic = records.flatMap((line) => {
    try {
      const record = JSON.parse(line);
      return record.kind === "diagnostic" ? [record] : [];
    } catch {
      return [];
    }
  })[0];
  if (diagnostic) {
    throw new Error(
      `${source}:${diagnostic.start}: ${diagnostic.code}: ${diagnostic.message}`,
    );
  }
  throw new Error(new TextDecoder().decode(run.stderr) || "Blot check failed");
}

/**
 * Generate a checked source module from checked declarations and explicit IDs.
 * The output is adjacent to its input so relative imports keep their meaning.
 */
export async function deriveFile(options: {
  source: string;
  output: string;
  schema: string;
  compiler: string;
  stdRoot: string;
  prelude: string;
}): Promise<void> {
  const { source, output, schema, compiler, stdRoot, prelude } = options;
  if (dirname(source) !== dirname(output) || source === output) {
    throw new Error("Output must be a different .blot file beside the source");
  }
  await check(compiler, source, stdRoot, prelude);
  const text = await Deno.readTextFile(source);
  const shapes = await dataShapes(text);
  const manifest = JSON.parse(await Deno.readTextFile(schema)) as {
    types: Record<string, Partial<DeriveSchema> & { operations?: string[] }>;
  };
  const names = Object.keys(manifest.types ?? {});
  if (!names.length) throw new Error("Schema must list at least one type");
  const plans = names.map((name) => {
    const shape = shapes.find((item) => item.name === name);
    if (!shape) throw new Error(`${name}: no checked data declaration`);
    const plan = manifest.types[name];
    const operations = plan.operations ?? ["equality", "debug", "codec"];
    if (
      !Array.isArray(operations) || operations.length === 0 ||
      operations.some((operation) =>
        !["equality", "debug", "codec"].includes(operation)
      )
    ) {
      throw new Error(
        `${name}: operations must select equality, debug, or codec`,
      );
    }
    const selected = new Set(operations);
    const prefix = deriveEqualityAndDebug(shape, {
      equality: selected.has("equality"),
      debug: selected.has("debug"),
    });
    if (!selected.has("codec")) return { source: prefix, selected };
    if (plan.version === undefined || !plan.variants) {
      throw new Error(
        `${name}: codec derivation requires version and variants`,
      );
    }
    return {
      source: prefix + deriveCodec(shape, plan as DeriveSchema),
      selected,
    };
  });
  const generated = plans.map((plan) => plan.source).join("\n");
  const imports = [
    plans.some((plan) => plan.selected.has("equality"))
      ? 'import * as _derive_eq from "std/equality"\n'
      : "",
    plans.some((plan) => plan.selected.has("debug"))
      ? 'import * as _derive_text from "std/text"\n'
      : "",
    plans.some((plan) => plan.selected.has("codec"))
      ? 'import * as _derive_codec from "std/codec"\n'
      : "",
  ].join("");
  const contents =
    `// Generated by scripts/derive.ts from checked data declarations.\n` +
    imports +
    `${text.trimEnd()}\n${generated}`;
  const temporary = await Deno.makeTempFile({
    dir: dirname(output),
    prefix: ".derive-",
    suffix: ".blot",
  });
  try {
    await Deno.writeTextFile(temporary, contents);
    await check(compiler, temporary, stdRoot, prelude);
    await Deno.rename(temporary, output);
  } finally {
    try {
      await Deno.remove(temporary);
    } catch (error) {
      if (!(error instanceof Deno.errors.NotFound)) throw error;
    }
  }
}

if (import.meta.main) {
  const root = new URL("../", import.meta.url).pathname;
  try {
    await deriveFile({
      source: option("--source"),
      output: option("--output"),
      schema: option("--schema"),
      compiler: option("--blotc"),
      stdRoot: Deno.args.includes("--std-root")
        ? option("--std-root")
        : `${root}/std`,
      prelude: Deno.args.includes("--prelude")
        ? option("--prelude")
        : `${root}/std/prelude.blot`,
    });
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    Deno.exit(1);
  }
}
