#!/usr/bin/env python3
"""Generate explicit Goose wire fields from the root-owned flat Core schema.

Development-only source generator; no Python runs in the Blot compiler.
The generated codec still validates all lengths before allocating tables.
"""
import re
import sys
from pathlib import Path
root=str(Path(__file__).resolve().parent.parent)+'/'
model=open(root+'src/model.goose').read()
structs={n:[tuple(x.strip().split(': ')) for x in f.split(', ')] for n,f in re.findall(r'struct (\w+) \{ ([^\n]+) \}',model)}
core=re.search(r'struct Core \{(.*?)\n\}',model,re.S).group(1)
tables=re.findall(r'    (\w+): const (\w+)\[:\]',core)
width=lambda fs:sum({'u32':1,'bool':1,'u64':2,'Span':2}[t] for _,t in fs)
body='''// Generated by scripts/generate_artifact_codec.py from src/model.goose.
// Portable K1 Core envelope. All integers are little-endian; no host layout is serialized.
// Header and every table extent are checked before any decoded table allocation.
namespace artifact;
import src.model;
import src.hash;
import src.order;

let MAGIC: u32 = 0x5241314b;
let SCHEMA: u32 = 1;
let TABLES: u32 = %d;
let HEADER: u32 = 96 + TABLES * 4;

fn put32(out: u8[>..]&, x: u32) {
    for i in 4 { out.push((x >> (i * 8)) as! u8); }
}
fn get32(bytes: const u8[:], at: u32) -> u32 {
    return bytes[at] as u32 | (bytes[at + 1] as u32 << 8) |
        (bytes[at + 2] as u32 << 16) | (bytes[at + 3] as u32 << 24);
}
fn set32(out: u8[>..]&, at: u32, x: u32) {
    for i in 4 { out[at + i] = (x >> (i * 8)) as! u8; }
}
fn invalid(diags: Diagnostic[>..]&, detail: u32) -> bool {
    diags.push(Diagnostic {code: 2034, detail: detail, ..}); return false;
}
fn incompatible(diags: Diagnostic[>..]&) -> bool {
    diags.push(Diagnostic {code: 2035, ..}); return false;
}
// Stable portable transport. The temporary canonical owner graph dies before
// publication; the output owns every byte.
fn artifact_encode(c:Core,out:u8[>..]&)->bool {
    var accepted=false;
    with_core() { b=>
        if !core_order::canonical_order(c,b) { return false from artifact_encode; }
        accepted=encode_tables(core_view(b),out);
    };
    return accepted;
}
// Current-process clone format; never use this entrypoint for persisted identity.
// Optional rewrites need identical IDs while their def-use arrays are live.
fn encode_tables(c: Core, out: u8[>..]&) -> bool {
    if out.len != 0 { return false; }
    var size: u64 = HEADER;
'''%len(tables)
for name,typ in tables:
 if typ=='u8': expr=f'c.{name}.len as u64'
 else:expr=f'(c.{name}.len as u64) * {4 if typ=="u32" else width(structs[typ])*4}'
 body+=f'    size += {expr};\n'
body+='''    if size > LIMIT_ARTIFACT { return false; }
    put32(out, MAGIC); put32(out, SCHEMA); put32(out, SEM_POLICY); put32(out, OPT_POLICY);
    put32(out, ABI_VERSION); put32(out, 0); put32(out, size as u32); put32(out, TABLES);
    for i in 8 { put32(out, 0); }
    out.append(ABI_HASH);
'''
for name,typ in tables:body+=f'    put32(out, c.{name}.len as u32);\n'
for name,typ in tables:
 if typ=='u8':body+=f'    out.append(c.{name});\n';continue
 body+=f'    for row in c.{name} {{\n'
 if typ=='u32':body+='        put32(out, row);\n'
 else:
  for f,t in structs[typ]:
   if t=='Span':body+=f'        put32(out, row.{f}.start); put32(out, row.{f}.count);\n'
   elif t=='u64':body+=f'        put32(out, row.{f} as! u32); put32(out, (row.{f} >> 32) as! u32);\n'
   elif t=='bool':body+=f'        if row.{f} {{ put32(out, 1); }} else {{ put32(out, 0); }}\n'
   else:body+=f'        put32(out, row.{f});\n'
 body+='    }\n'
body+='''    let digest = k1hash::blake3(out[64..]);
    for i in 8 { set32(out, (32 + i * 4) as u32, digest.words[i]); }
    return true;
}
fn artifact_decode(bytes: const u8[:], b: CoreBuilder, diags: Diagnostic[>..]&) -> bool {
    if bytes.len < HEADER || bytes.len > LIMIT_ARTIFACT { return invalid(diags, 1); }
    if get32(bytes, 0) != MAGIC { return invalid(diags, 2); }
    if get32(bytes, 4) != SCHEMA || get32(bytes, 8) != SEM_POLICY ||
        get32(bytes, 12) != OPT_POLICY || get32(bytes, 16) != ABI_VERSION {
        return incompatible(diags);
    }
    if get32(bytes, 20) != 0 || get32(bytes, 24) != bytes.len || get32(bytes, 28) != TABLES {
        return invalid(diags, 3);
    }
    for i in 32 { if bytes[64 + i] != ABI_HASH[i] { return incompatible(diags); } }
    let digest = k1hash::blake3(bytes[64..]);
    for i in 8 { if get32(bytes, (32 + i * 4) as u32) != digest.words[i] { return invalid(diags, 4); } }
    var required: u64 = HEADER;
'''
for i,(name,typ) in enumerate(tables):
 body+=f'    let n_{name} = get32(bytes, {96+i*4});\n'
 minc=0 if typ in ['u8','u32'] else 1
 maxc=16777216 if typ=='u8' else 4194304
 body+=f'    if n_{name} < {minc} || n_{name} > {maxc} || b.{name}.len != {minc} {{ return invalid(diags, {10+i}); }}\n'
 body+=f'    required += (n_{name} as u64) * {1 if typ=="u8" else 4 if typ=="u32" else width(structs[typ])*4};\n'
body+='''    if required != bytes.len { return invalid(diags, 50); }
    // Preflight above covers all records; below never follows a decoded ID/span.
    var at: u32 = HEADER;
'''
for i,(name,typ) in enumerate(tables):
 if typ=='u8':body+=f'    b.{name}.append(bytes[at..at + n_{name}]);\n';continue
 body+=f'    for index in n_{name} {{\n'
 if typ=='u32':body+=f'        b.{name}.push(get32(bytes, at)); at += 4;\n'
 else:
  body+=f'        let row_start = at;\n        var row = {typ} {{ .. }};\n'
  for f,t in structs[typ]:
   if t=='Span':body+=f'        row.{f} = Span {{ get32(bytes, at), get32(bytes, at + 4) }}; at += 8;\n'
   elif t=='u64':body+=f'        row.{f} = get32(bytes, at) as u64 | (get32(bytes, at + 4) as u64 << 32); at += 8;\n'
   elif t=='bool':body+=f'        if get32(bytes, at) > 1 {{ return invalid(diags, 51); }}\n        row.{f} = get32(bytes, at) != 0; at += 4;\n'
   else:body+=f'        row.{f} = get32(bytes, at); at += 4;\n'
  body+=f'        if index == 0 {{ for byte in bytes[row_start..at] {{ if byte != 0 {{ return invalid(diags, 52); }} }} }} else {{ b.{name}.push(row); }}\n'
 body+='    }\n'
body+='''    // Imported receipts carry observations only. No source admission or encoded executable is trusted.
    b.phase.phase = PHASE_SEALED;
    return true;
}
'''
destination=Path(root+'src/artifact.goose')
if '--check' in sys.argv:
    if not destination.exists() or destination.read_text()!=body:
        print('stale generated file: '+str(destination),file=sys.stderr)
        raise SystemExit(1)
else:
    destination.write_text(body)
