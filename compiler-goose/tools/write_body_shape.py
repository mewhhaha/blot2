"""Derive the emitter's scalar-edit comparison from the portable Core schema."""
import json
from pathlib import Path
import re


def write_body_shape(root: Path) -> None:
    descriptors = json.loads((root / 'tools/dependency-wire-model.json').read_text())['descriptors']
    types = {d['name']: d for d in descriptors}
    output = ['// Generated by write_body_shape.py from the portable Core schema.',
              'namespace blot_reuse_body_shape;', 'import check.core;', 'import support.option;',
              'fn sameSlice<T>(a:const T[:],b:const T[:])->bool { return a==b; }']
    seen = {}

    def compare(name):
        if name in seen:
            return seen[name]
        item = types[name]
        function = 'same_' + re.sub(r'\W', '_', name)
        body = []
        t = item['goose']
        if name == 'parse.ast.Span':
            body.append('return true;')
        elif item['kind'] == 'struct':
            fields = [(member, compare(child)) for _, child, member in item['fields']]
            if not (any(fn for _, fn in fields) or item.get('unwired') or
                    name in ('check.core.Node', 'check.core.Projection', 'check.core.RuntimeName')):
                seen[name] = None
                return None
            for field, fn in fields:
                if (name, field) in (('check.core.RuntimeName', 'point'), ('check.core.Projection', 'diagnostic_point')):
                    continue
                test = f'!{fn}(a.{field},b.{field})' if fn else f'a.{field}!=b.{field}'
                if (name, field) == ('check.core.Node', 'a'):
                    test = 'a.tag!=blot_check_core::Tag.constant && ' + test
                body.append(f'if {test} {{ return false; }}')
            body.append('return true;')
        elif item['kind'] in ('slice', 'array', 'optional'):
            fn = compare(item['children'][0])
            if not fn:
                # Goose compares a slice field inside a struct by address. Use
                # slice value equality even when its elements need no adapter.
                seen[name] = 'sameSlice' if item['kind'] == 'slice' else None
                return seen[name]
            if item['kind'] == 'optional':
                body.append(f'return a.present==b.present && (!a.present || {fn}(a.value,b.value));')
            else:
                body.extend(['if a.len!=b.len { return false; }',
                             f'for i in 0..a.len {{ if !{fn}(a[i],b[i]) {{ return false; }} }}', 'return true;'])
        else:
            seen[name] = None
            return None
        output.append(f'fn {function}(a:{t},b:{t})->bool {{\n    ' + '\n    '.join(body) + '\n}')
        seen[name] = function
        return function

    compare('check.core.Module')
    (root / 'src/reuse/body_shape.goose').write_text('\n'.join(output) + '\n')
