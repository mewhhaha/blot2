#!/usr/bin/env python3
"""Reconstruct detached dependency headers from their exact existing owner runs."""
from pathlib import Path
import re
from source_model import balanced, clean, fields

ROOT = Path(__file__).resolve().parents[1] / 'src'
SCHEMAS = [
    ('check/frozen_types', 'Graph'),
    ('check/frozen_types', 'PatternGraph'),
    ('check/capability_contracts', 'Collection'),
    ('check/core', 'EffectRows'),
    ('check/core', 'Types'),
    ('check/core', 'Module'),
    ('reuse/principal_interface', 'Interface'),
    ('reuse/frozen_dependency', 'Identity'),
    ('reuse/frozen_dependency', 'Module'),
    ('reuse/frozen_dependency', 'FrozenDependency'),
]
NESTED = {
    ('check/core', 'Types'): 'blot_check_core::Types',
    ('check/core', 'EffectRows'): 'blot_check_core::EffectRows',
    ('reuse/frozen_dependency', 'Identity'): 'blot_reuse_frozen_dependency::Identity',
}
SCALARS = {'bool', 'u32', 'u64', 'i64', 'u8[32]'}


def main():
    records = []
    imports = ['reuse.dependency_payload', 'support.option']
    for module, name in SCHEMAS:
        source = clean((ROOT / (module + '.goose')).read_text())
        namespace = re.search(r'\bnamespace\s+(\w+)\s*;', source)[1]
        declaration = re.search(r'\bstruct\s+' + name + r'\s*\{', source)
        records.append((module, name, namespace + '::' + name,
                        fields(source[declaration.end():balanced(source, declaration.end() - 1)])))
        if module.replace('/', '.') not in imports:
            imports.append(module.replace('/', '.'))
    known = {qualified for _, _, qualified, _ in records}
    lines = ['// Generated by tools/write_dependency_owned_headers.py; no allocation or payload copying.',
             'namespace blot_reuse_dependency_owned_headers;']
    lines += ['import ' + module + ';' for module in imports]
    lines += ['type Owner=blot_reuse_dependency_payload::Owner;']
    for module, name, qualified, members in records:
        values = []
        for field, raw_type in members:
            field_type = re.sub(r'\s+', '', raw_type)
            expression = 'value.' + field
            if '[:]' in field_type:
                expression = 'owner.mutable(' + expression + ')'
            elif NESTED.get((module, field_type), field_type) in known:
                expression = 'canonical(owner,' + expression + ')'
            elif field_type not in SCALARS:
                raise ValueError(f'Unreviewed owned header field {qualified}.{field}: {raw_type}')
            values.append(field + ':' + expression)
        lines += [f'fn canonical(owner:const Owner&,value:{qualified})->{qualified} {{',
                  ' assert(owner.unique());',
                  f' return {qualified}{{' + ','.join(values) + '};', '}']
    destination = ROOT / 'reuse/dependency_owned_headers.goose'
    destination.write_text('\n'.join(lines) + '\n')
    # Worker packets retain their own typed journal, distinct from dependency owners.
    packet_records = [record for record in records if (record[0], record[1]) in [('check/core', 'EffectRows'), ('check/capability_contracts', 'Collection')]]
    core_source = clean((ROOT / 'check/core.goose').read_text())
    for name in ['TypesStampView', 'StampView']:
        declaration = re.search(r'\bstruct\s+' + name + r'\s*\{', core_source)
        packet_records.append(('check/core', name, 'blot_check_core::' + name, fields(core_source[declaration.end():balanced(core_source, declaration.end() - 1)])))
    packet_nested = dict(NESTED)
    packet_nested[('check/core', 'TypesStampView')] = 'blot_check_core::TypesStampView'
    packet_known = {qualified for _, _, qualified, _ in packet_records}
    packet = ['// Generated by tools/write_dependency_owned_headers.py; checked packet journal views, no copying.',
              'namespace blot_core_packet_headers;', 'import support.core_packet;',
              'import check.core;', 'import check.capability_contracts;']
    for module, name, qualified, members in packet_records:
        values = []
        for field, raw_type in members:
            field_type = re.sub(r'\s+', '', raw_type)
            expression = 'value.' + field
            if '[:]' in field_type:
                expression = 'blot_core_packet::mutable(owner,' + expression + ')'
            elif packet_nested.get((module, field_type), field_type) in packet_known:
                expression = 'canonical(owner,' + expression + ')'
            elif field_type not in SCALARS:
                raise ValueError(f'Unreviewed packet header field {qualified}.{field}: {raw_type}')
            values.append(field + ':' + expression)
        packet += [f'fn canonical(owner:blot_core_packet::Owned&,value:{qualified})->{qualified} {{',
                   f' return {qualified}{{' + ','.join(values) + '};', '}']
    (ROOT / 'support/core_packet_headers.goose').write_text('\n'.join(packet) + '\n')
    archive = '\n'.join(packet).replace('namespace blot_core_packet_headers;', 'namespace blot_archive_core_headers;').replace('import support.core_packet;', 'import reuse.dependency_format;').replace('owner:blot_core_packet::Owned&', 'owner:const blot_reuse_dependency_format::Owner&').replace('blot_core_packet::mutable(owner,', 'blot_reuse_dependency_format::mutable(owner,')
    (ROOT / 'support/archive_core_headers.goose').write_text(archive + '\n')



if __name__ == '__main__':
    main()
