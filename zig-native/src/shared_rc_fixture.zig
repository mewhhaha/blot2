//! Checked runtime operations; source admission is exercised separately.
const std = @import("std");
const wasm = @import("wasm.zig");
const gen = @import("runtime_code.zig");
pub fn main(init: std.process.Init) !void {
    const args = try init.minimal.args.toSlice(init.arena.allocator());
    var module = wasm.Module.init(init.gpa);
    defer module.deinit();
    const arena = try module.ensureArena();
    module.globals.items[arena.root_enabled].bits = 1;
    inline for (.{ "root_allocate", "root_reserve", "root_open", "root_close", "root_enter", "root_leave", "root_force" }) |name|
        try module.exportFunction(@field(arena, name), name, .u32, .u32);
    try module.exportGlobal(arena.root_count, "roots");
    inline for (.{ "cycle_head", "cycle_passes", "cycle_vertices", "cycle_edges", "cycle_bytes" }) |name| try module.exportGlobal(@field(arena, name), name);
    try module.exportGlobal(arena.heap, "heap");
    const demand = try module.dataObject(@import("runtime_layout.zig").Demand{ .function = 0, .environment = 0, .status = .pending, .cached = 0 });
    try module.exportGlobal(try module.addGlobal(.u32, demand, false), "static_demand");
    const noop = try module.addFunction(&.{.i32}, .none);
    try module.exportFunction(noop, "noop", .u32, .u32);
    inline for (.{ "allocate_typed", "retain", "release", "release_lease", "store_word", "copy_words", "reset", "cycle_safe", "cycle_collect" }) |name|
        try module.exportFunction(@field(arena, name), name, .u32, .u32);
    const collect = try module.addFunction(&.{.i32}, .i32);
    try module.emitSlice(collect, &.{ .{ .op = .local_get }, .{ .op = .global_get, .operand = arena.base }, .{ .op = .i32_const }, .{ .op = .call, .operand = arena.collect } });
    try module.exportFunction(collect, "collect", .u32, .u32);
    const chain = try module.addFunction(&.{.i32}, .i32);
    const c: gen.Code = .{ .module = &module, .function = chain };
    const index = try c.temp();
    const head = try c.temp();
    const next = try c.temp();
    try c.loop(.{ .i32_lt_u, index, gen.Local{ .id = 0 } });
    try c.set(next, .{ .call, arena.allocate_typed, 4, 1 });
    try c.value(.{ .call, arena.store_word, next, next, head });
    try c.when(head);
    try c.value(.{ .call, arena.release_lease, head });
    try c.end();
    try c.set(head, next);
    try c.set(index, .{ .i32_add, index, 1 });
    try c.again();
    try c.when(head);
    try c.value(.{ .call, arena.release_lease, head });
    try c.end();
    try c.value(.{ .global, arena.rc_leases });
    try module.exportFunction(chain, "chain", .u32, .u32);
    const references = try module.addFunction(&.{.i32}, .i32);
    const fields: gen.Code = .{ .module = &module, .function = references };
    const parent = try fields.temp();
    const child = try fields.temp();
    const position = try fields.temp();
    try fields.trap(.{ .i32_or, .{ .i32_eqz, gen.Local{ .id = 0 } }, .{ .i32_gt_u, gen.Local{ .id = 0 }, 1048576 } });
    try fields.set(parent, .{ .call, arena.allocate_typed, .{ .i32_mul, gen.Local{ .id = 0 }, 4 }, 0xffffffff });
    try fields.set(child, .{ .call, arena.allocate_typed, 4, 0 });
    try fields.value(.{ .call, arena.store_word, child, child, 42 });
    try fields.loop(.{ .i32_lt_u, position, gen.Local{ .id = 0 } });
    try fields.value(.{ .call, arena.store_word, parent, .{ .cell, parent, position, 0 }, child });
    try fields.next(position);
    try fields.again();
    try fields.value(.{ .call, arena.release_lease, child });
    try fields.value(parent);
    try module.exportFunction(references, "references", .u32, .u32);
    const bytes = try module.assembleWithOptions(.{ .export_memory = true });
    defer init.gpa.free(bytes);
    try std.Io.Dir.cwd().writeFile(init.io, .{ .sub_path = args[1], .data = bytes });
}
