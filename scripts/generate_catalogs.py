"""Generate the human-readable registry from the compiler's explicit IDs."""
import argparse
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
sources = {p.name: p.read_text() for p in sorted((root / "src").glob("*.goose"))}
constants = {}
for source in sources.values():
    for name, value in re.findall(r"(?:let|const)\s+(\w+)\s*:\s*u32\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*;", source):
        constants[name] = int(value, 0)

registry = ["# K1 operation and policy registry", "", "Generated by `scripts/generate_catalogs.py` from `src/model.goose`.",
            "IDs are explicit wire identities. Zero is reserved; changing semantics requires", "a versioned policy/ABI change. Independent validation checks every operation.", "",
            "Policies: K1-SEM-POLICY-1, K1-OPT-POLICY-1 and K1-WASM32-ABI1.", ""]
for title, prefix in [("Operations", "OP_"), ("Types", "TY_"), ("Evidence rules", "RULE_"), ("Required limits", "LIMIT_")]:
    registry.extend([f"## {title}", "", "| Name | Value |", "| --- | ---: |"])
    rows = re.findall(r"let\s+(" + prefix + r"\w+)\s*:\s*u32\s*=\s*(\d+)\s*;", sources["model.goose"])
    registry.extend(f"| `{name}` | {value} |" for name, value in rows)
    registry.append("")

diagnostics = ["# K1 diagnostic catalogue", "", "Generated from diagnostic-name consumers. Numeric codes identify the producing", "subsystem; the `k1_*` category is the stable source-facing contract. Imported", "artifact failures wrap their validation cause as `k1_invalid_artifact`.", "",
               "| Code | Category | Producer |", "| ---: | --- | --- |"]
rows = set()
for filename, source in sources.items():
    for value, name in re.findall(r'if\s+code\s*==\s*(\w+)\s*\{\s*return\s+"(k1_[a-z_]+)"', source):
        number = int(value) if value.isdecimal() else constants.get(value)
        if number is not None:
            rows.add((number, name, filename))
diagnostics.extend(f"| {number} | `{name}` | `{filename}` |" for number, name, filename in sorted(rows))
diagnostics.extend(["", "Syntax-only parser failures also carry a byte range and explanatory message.",
                    "Tests assert categories and relevant spans, not incidental wording.", ""])
for name, lines in [("REGISTRY.md", registry), ("DIAGNOSTICS.md", diagnostics)]:
    path = root / "docs" / name
    expected = "\n".join(lines)
    if args.check:
        if not path.exists() or path.read_text() != expected:
            raise SystemExit(f"stale {name}; run scripts/generate_catalogs.py")
    else:
        path.write_text(expected)
